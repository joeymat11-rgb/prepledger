    const c=options.clock||clock(day), idProvider=options.ids||ids(c), drafts=options.drafts||Object.freeze({length:0,key:()=>null});
    const table=factory({clock:c,ids:idProvider,drafts}).__test;
    if(!table||Object.hasOwn(table,'__auditOriginal'))fail('REPAIR-CONTROL-TARGET');
    const n=++instance, facade={...table};
