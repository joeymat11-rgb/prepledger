// A snapshot carries tagged values and stable object identities across calls.
// Tags are arrays generated by the encoder, never user-object magic properties.
function graphEncoder() {
  const identities=new Map(); let next=0;
  const identity = value => { if(!identities.has(value))identities.set(value,++next);return identities.get(value); };
  return function snapshot(root) {
    const visited=new Set();
    function visit(v) {
      if(v===null)return ['null'];
      const type=typeof v;
      if(type==='undefined')return ['undefined'];
      if(type==='number')return ['number',Number.isNaN(v)?'NaN':v===Infinity?'+Infinity':v===-Infinity?'-Infinity':Object.is(v,-0)?'-0':String(v)];
      if(type==='string'||type==='boolean'||type==='bigint')return [type,String(v)];
      if(type==='symbol')return ['symbol',identity(v),v.description??null];
      if(type==='function')return ['function',identity(v)];
      const id=identity(v); if(visited.has(v))return ['ref',id]; visited.add(v);
      const tag=Object.prototype.toString.call(v);
      if(tag==='[object Date]')return ['Date',id,visit(v.getTime())];
      if(tag==='[object Map]')return ['Map',id,[...v].map(([k,x])=>[visit(k),visit(x)])];
      if(tag==='[object Set]')return ['Set',id,[...v].map(visit)];
      if(ArrayBuffer.isView(v))return [tag,id,Buffer.from(v.buffer,v.byteOffset,v.byteLength).toString('hex')];
      if(tag==='[object ArrayBuffer]')return [tag,id,Buffer.from(v).toString('hex')];
      if(!['[object Array]','[object Object]','[object Error]'].includes(tag))fail('UNSUPPORTED-TRACE-TYPE');
      if(tag==='[object Object]'&&Object.getPrototypeOf(v)!==null&&Object.getPrototypeOf(v)!==Object.prototype)fail('UNSUPPORTED-TRACE-PROTOTYPE');
      const props=Reflect.ownKeys(v).filter(k=>!(tag==='[object Error]'&&k==='stack')).map(k=>{
        const d=Object.getOwnPropertyDescriptor(v,k);if(!Object.hasOwn(d,'value'))fail('UNSUPPORTED-TRACE-ACCESSOR');
        return [visit(k),!!d.enumerable,!!d.writable,!!d.configurable,visit(d.value)];
      });
      return [tag,id,Object.getPrototypeOf(v)===null?'null-prototype':'standard',props];
    }
    return visit(root);
  };
}
function compile(file, requireFn) {
  const mod={exports:{}};
  const fn=new vm.Script('(function(exports,require,module,__filename,__dirname){\n'+fs.readFileSync(file,'utf8')+'\n})',{filename:file}).runInThisContext();
  fn(mod.exports,requireFn,mod,file,path.dirname(file));return mod.exports;
}
function loadCandidate(directory, inventory, loaded = []) {
  const root=fs.realpathSync(directory), cache=new Map();
  function load(file) {
    const real=fs.realpathSync(file), relative=path.relative(root,real).split(path.sep).join('/');
    if(!Object.hasOwn(inventory,relative)||relative.startsWith('../')||path.isAbsolute(relative))fail('CANDIDATE-IMPORT-OUTSIDE-INVENTORY');
    if(sha(fs.readFileSync(real))!==inventory[relative])fail('CANDIDATE-SOURCE-PIN');
    if(cache.has(real))return cache.get(real);
    loaded.push(relative);
    const exported=compile(real,request=>{
      if(!request.startsWith('./'))fail('CANDIDATE-IMPORT-OUTSIDE-INVENTORY');
      return load(path.resolve(path.dirname(real),request));
    });cache.set(real,exported);return exported;
  }
  const factory=load(path.join(root,'index.cjs'));
  if(typeof factory.createEngine!=='function')fail('CANDIDATE-FACTORY-MISSING');
  return factory.createEngine;
}
