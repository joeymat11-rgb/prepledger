export const scopeFor = tag => ({ databaseName: 'p3-rs-' + tag, namespace: 'joe/p3-rs-' + tag,
  athleteId: 'ath-p3-rs', deviceId: 'dev-p3-rs' });

export async function reopen(indexedDB, scope, at) {
  const era = await eraFor({ indexedDB, live: liveAt(AT(at)), ...scope });
  const win = shellWindow();
  Object.defineProperty(win, 'indexedDB', { configurable: true, value: indexedDB });
  const booted = await Entry.boot({ document: win.document, hosts: era, now: liveAt(AT(at)) });
  await booted.api.ready;
  return { era, win, doc: win.document, booted,
    close: () => { booted.rollover.stop(); booted.teardown(); era.close(); } };
}

export async function phone(tag, { at = IMPORT_DAY, setup = PHONE } = {}) {
  const indexedDB = new IDBFactory();
  const scope = scopeFor(tag);
  const first = await eraFor({ indexedDB, live: liveAt(AT(SETUP_DAY)), ...scope });
  await firstRunWith(first, SETUP_DAY, setup.setup, setup.tags);
  first.close();
  return { ...(await reopen(indexedDB, scope, at)), indexedDB, scope };
}

export async function afterTap(booted, node) {
  tap(node);
  const screen = booted.api.importScreen();
  if (screen) await screen.settled();
  await booted.api.render('import', false);
  return booted.api.importScreen();
}

export async function toReview(win, booted, bundle) {
  const doc = win.document;
  await booted.api.render('import', true);
  pickBundle(win, doc.getElementById('import-file'), bundle.bytes);
  await booted.api.render('import', false);
  type(doc.getElementById('import-passphrase'), bundle.passphrase);
  const unlocked = await afterTap(booted, slot(doc, 'import-unlock'));
  if (unlocked.step() !== 'identity') return { step: unlocked.step(), screen: unlocked };
  return { step: 'identity', screen: await afterTap(booted, slot(doc, 'import-identity-yes')) };
}

/* ONE WALK: pick, six words, Unlock, identity Yes, Import this history.
   Returns what the screen said, without asserting anything: these cells
   MEASURE the shipped behaviour, they do not prescribe it. */
export async function walk(tag, bundle, options = {}) {
  const kit = await phone(tag, options);
  const reviewed = await toReview(kit.win, kit.booted, bundle);
  if (reviewed.step !== 'identity')
    return { kit, stage: reviewed.step, refusal: reviewed.screen.refusal(), screen: reviewed.screen };
  if (reviewed.screen.step() !== 'review')
    return { kit, stage: reviewed.screen.step(), refusal: reviewed.screen.refusal(), screen: reviewed.screen };
  const at = await afterTap(kit.booted, slot(kit.doc, 'import-confirm'));
  const line = slot(kit.doc, 'import-refusal');
  return { kit, stage: at.step(), refusal: at.refusal(), screen: at,
    line: line ? line.textContent : null };
}
