/* THE BRACKET, one variable per step, each cumulative on the one before it. */
export function variant(level) {
  const state = Fixture.legacyState();
  if (level >= 1) for (const p of state.split) delete p.why;
  if (level >= 2) {
    const remap = id => PHONE_ID[id] || id;
    for (const e of state.exercises) e.id = remap(e.id);
    for (const q of state.queue) if (q.exId) q.exId = remap(q.exId);
    for (const day of Object.values(state.sessionLog))
      for (const entry of day.entries) entry.id = remap(entry.id);
    state.exOrder = { U: state.exOrder.U.map(remap), L: state.exOrder.L.map(remap) };
    state.insertions = Object.fromEntries(Object.entries(state.insertions).map(([k, v]) => [remap(k), v]));
  }
  /* The new app's rung ladder, which the old app has nowhere. Synthetic and
     ascending, built off each lift's own increment. */
  if (level >= 3) for (const e of state.exercises)
    e.steps = [1, 2, 3, 4, 5].map(n => 10 + n * (typeof e.inc === 'number' && e.inc > 0 ? e.inc : 5));
  /* The one lift the old app carries with inc: null (bodyweight). */
  if (level >= 4) for (const e of state.exercises) if (!(typeof e.inc === 'number' && e.inc > 0)) e.inc = 5;
  if (level >= 5) state.athlete_label = PHONE.setup.athlete_label;
  if (level >= 6) state.priority_muscles = PHONE.setup.priority_muscles.slice();
  /* THE OLD APP'S THREE NON-NUMERIC WORKING LOADS ('BW', 'hold', and the
     wSets vector), replaced by plain numbers. The new app's page composes the
     v1 capture producer (today-bindings.mjs:94, Adapter.PROFILE), and
     engine-capture.cjs:66 refuses a card whose `w` is a configuration string
     unless the v2 CONFIGURATION_PROFILE is the registered producer. */
  if (level >= 7) for (const e of state.exercises) {
    if (typeof e.w === 'string') e.w = 25;
    if (Array.isArray(e.wSets)) delete e.wSets;
    if (e.lastMeta && typeof e.lastMeta.w === 'string') e.lastMeta.w = 25;
    for (const day of Object.values(state.sessionLog))
      for (const entry of day.entries) if (typeof entry.w === 'string') entry.w = 25;
  }
  return state;
}

const sealedCache = new Map();
export function sealed(level) {
  if (!sealedCache.has(level)) sealedCache.set(level, sealInventedBundle(undefined, { state: variant(level) }));
  return sealedCache.get(level);
}

